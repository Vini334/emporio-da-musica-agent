"""Markdown rendering of the data quality report (``docs/data_quality_report.md``)."""

from __future__ import annotations

from collections import defaultdict
from collections.abc import Iterable
from pathlib import Path
from typing import TYPE_CHECKING

from emporio import config
from emporio.data.quality import SECTIONS, Finding, join_ints
from emporio.formatting import date_br

if TYPE_CHECKING:
    from emporio.data.prepare import PrepareResult

REPORT_PATH = config.DOCS_DIR / "data_quality_report.md"


def render_report(result: PrepareResult) -> str:
    tables = result.tables
    products = tables["products"]
    orders = tables["orders"]
    customers = tables["customers"]
    status_counts = _count(products, "status")
    order_status_counts = _count(orders, "status")
    cities = _count(customers, "city")
    used_categories = {p["category_id"] for p in products}
    empty_categories = sum(
        1 for c in tables["categories"] if c["category_id"] not in used_categories
    )

    lines = [
        "# Data quality report",
        "",
        "> Generated by `python -m emporio.data.prepare` (do not edit by hand). Reference date "
        f"for late orders: **{date_br(result.as_of)}**.",
        "",
        "The raw data (`data/raw`) is never edited. The `data/processed` layer only "
        "**standardizes** (types, enums, parsed specs, fields normalized for search) and "
        "**flags** suspicious records; no content is rewritten or recalculated. Each finding "
        "below states the treatment adopted. The reasoning behind the decisions is in "
        "[`design-decisions.md`](design-decisions.md) (§5 and §6). The store data is in "
        "Portuguese, so quotes from it are kept as is.",
        "",
        "## Summary",
        "",
        "| Table | Records | Notes |",
        "|---|---|---|",
        f"| categories | {len(tables['categories'])} | {empty_categories} without products |",
        f"| products | {len(products)} | {_fmt_counts(status_counts)} |",
        f"| promotions | {len(tables['promotions'])} | "
        f"{sum(1 for p in tables['promotions'] if p['is_active'])} active |",
        f"| customers | {len(customers)} | {_fmt_counts(cities)} |",
        f"| orders | {len(orders)} | {_fmt_counts(order_status_counts)} |",
        f"| order items | {len(tables['order_items'])} | — |",
        f"| manual (PDF) | {len(result.policy_pages)} pages | text extracted with `pypdf` |",
        "",
        f"**{len(result.findings)} findings** · "
        + " · ".join(
            f"{severity}: {count}"
            for severity, count in sorted(_count_attr(result.findings, "severity").items())
        ),
        "",
        "Severity: **conflict** = the data contradicts other data or the manual; **rule** = the "
        "history breaks a rule of the manual; **warning** = a state that needs special handling "
        "in customer service; **info** = context.",
        "",
        "## Findings",
    ]
    for section, title in SECTIONS.items():
        section_findings = [f for f in result.findings if f.section == section]
        if not section_findings:
            continue
        lines += ["", f"### {title}"]
        for finding in section_findings:
            lines += _render_finding(finding)

    lines += ["", "## Checks with no issues", ""]
    if result.passed_checks:
        lines += [f"- {SECTIONS[section]}: {label}" for section, label in result.passed_checks]
    else:
        lines.append("- (none)")

    lines += [
        "",
        "## Processed layer (`data/processed`)",
        "",
        "One JSON per table (`ensure_ascii=False`, dates in ISO 8601). Added fields:",
        "",
        "- `products`: `name_normalized`, `brand`, `category_name`, `specs` (objeto), "
        "`specs_schema`, `description_conflict`, `description_conflict_reasons`, `search_text`.",
        "- `customers`: `first_name`, `phone_digits`, `email_normalized`.",
        "- `orders`: `payment_type`, `installments`, `items_total_brl`, `total_mismatch`, "
        "`pix_without_discount`, `installment_below_minimum`.",
        "- `order_items`: `unit_price_brl` and `line_total_brl` (**current** catalog price).",
        "- `promotions`: `is_active` as a boolean.",
        "- `policy_pages.json`: the text of each manual page, with spacing fixed "
        "(`pypdf` returns one word per line).",
        "",
    ]
    return "\n".join(lines)


def _render_finding(finding: Finding) -> list[str]:
    lines = ["", f"#### {finding.title} · _{finding.severity}_", ""]
    if finding.ids:
        lines.append(f"- **Records:** {join_ints(finding.ids)}")
    lines += [f"- **What was seen:** {finding.detail}", f"- **Treatment:** {finding.treatment}"]
    if finding.table_rows:
        lines += [
            "",
            "| " + " | ".join(finding.table_header) + " |",
            "|" + "---|" * len(finding.table_header),
        ]
        lines += ["| " + " | ".join(_cell(c) for c in row) + " |" for row in finding.table_rows]
    return lines


def _cell(value: str) -> str:
    return value.replace("|", "\\|")


def _count(rows: Iterable[dict], key: str) -> dict[str, int]:
    counts: dict[str, int] = defaultdict(int)
    for row in rows:
        counts[str(row[key])] += 1
    return dict(sorted(counts.items(), key=lambda kv: (-kv[1], kv[0])))


def _count_attr(items: Iterable[object], attr: str) -> dict[str, int]:
    counts: dict[str, int] = defaultdict(int)
    for item in items:
        counts[getattr(item, attr)] += 1
    return dict(counts)


def _fmt_counts(counts: dict[str, int]) -> str:
    return ", ".join(f"{value} {key}" for key, value in counts.items())


def write_report(result: PrepareResult, path: Path = REPORT_PATH) -> Path:
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(render_report(result), encoding="utf-8")
    return path
